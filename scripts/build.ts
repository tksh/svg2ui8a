/**
 * Build pipeline for `@tksh/svg2ui8a` (engineering-playbook §2, task.md §16).
 *
 *  1. Compiles the two Wasm crates via `wasm-pack --target web`.
 *  2. Copies the Wasm binaries to `assets/`.
 *  3. Regenerates `src/svg2usvg.ts`, `src/svg2rgba.ts`, and `src/mod.ts`
 *     from the wasm-pack glue. The Wasm bytes are *not* embedded: each
 *     wrapper loads its binary from a separate `.wasm` file, defaulting to
 *     the copy shipped in `assets/` (resolved relative to the module) and
 *     allowing consumers to pass an explicit URL
 *     (`docs/plans/wasm-file-delivery.md`).
 *  4. Verifies the two artifacts are independent Wasm modules
 *     (`constitution` §3.9, two independently-loadable capabilities).
 *  5. Runs the CDN-free check; aborts the build on failure.
 *
 * wasm-pack 0.15.0 is the recorded toolchain version for this script.
 */

import { runCheck } from "./check-cdn-free.ts";

const resolve = (relativePath: string): string =>
  new URL(relativePath, import.meta.url).pathname;
const ROOT = resolve("../");
const ASSETS_DIR = resolve("../assets/");

/** Run a command from `cwd`, returning trimmed stdout; throws on failure. */
function run(argv: string[], cwd = ROOT): string {
  const [cmd, ...args] = argv;
  const res = new Deno.Command(cmd, {
    args,
    cwd,
    stdout: "piped",
    stderr: "piped",
  }).outputSync();
  if (!res.success) {
    const stderr = new TextDecoder().decode(res.stderr);
    throw new Error(`command failed: ${cmd} ${args.join(" ")}\n${stderr}`);
  }
  return new TextDecoder().decode(res.stdout).trim();
}

/**
 * Inline wasm-pack glue so the generated wrapper is self-contained: strip the
 * module header and final export line, and apply the given renames so the
 * glue's symbols never collide with the public API.
 */
function inlineGlue(glue: string, renames: Array<[string, string]>): string {
  let out = glue.replace(/^\/\* @ts-self-types=.*\*\/\s*/, "");
  for (const [from, to] of renames) {
    out = out.replaceAll(from, to);
  }
  return out.replace(/export \{ initSync, __wbg_init as default \};\s*$/, "");
}

const GENERATED_HEADER = "// deno-fmt-ignore-file\n" +
  "// deno-lint-ignore-file\n" +
  "// @ts-nocheck\n" +
  "/* This file is auto-generated by `scripts/build.ts` — do not edit by hand. */\n\n";

const SVG2USVG_MODULE_DOC = `/**
 * Converts an SVG string into normalized usvg XML bytes.
 *
 * The sole export is {@linkcode svg2usvg}, which parses a supported SVG with
 * feature-disabled \`usvg\` and serializes it with the default \`XmlOptions\`.
 * Every payload is a \`Uint8Array\`; the output is UTF-8 encoded standard SVG
 * XML, not a proprietary binary format.
 *
 * The Wasm binary is not embedded in this module: it is loaded from a
 * separate \`.wasm\` file on first use. See {@linkcode initSvg2usvg} to load
 * it from somewhere else.
 *
 * @module
 */

`;

const SVG2RGBA_MODULE_DOC = `/**
 * Renders an SVG string to raw RGBA pixels in one shot.
 *
 * Exports {@linkcode svg2rgba} together with the {@linkcode Svg2RgbaOptions}
 * and {@linkcode RgbaResult} types. The output is a \`Uint8Array\` of packed,
 * row-major RGBA bytes; this module never encodes PNG, WebP, or JPEG.
 *
 * The Wasm binary is not embedded in this module: it is loaded from a
 * separate \`.wasm\` file on first use. See {@linkcode initSvg2rgba} to load
 * it from somewhere else.
 *
 * @module
 */

`;

/**
 * Generate the Wasm-loading half of a capability wrapper: the asset
 * reference, the cached initialization, and the public init function.
 *
 * The binary is fetched instead of embedded so that consumers can host and
 * cache it themselves. The bytes are read into an `ArrayBuffer` rather than
 * compiled from a stream, because `WebAssembly.instantiateStreaming` requires
 * the `application/wasm` content type and the hosting server is out of this
 * package's control.
 */
function generateWasmLoader(capability: string, assetFile: string): string {
  return `/**
 * Options for {@linkcode initSvg2${capability}}.
 */
export interface Svg2${capability}InitOptions {
  /**
   * Location of the \`${assetFile}\` binary to load.
   *
   * Defaults to the copy shipped with the package, resolved relative to this
   * module. Consumers whose bundler or hosting layout puts the binary
   * somewhere else must pass its deployed URL explicitly.
   */
  wasmUrl?: string | URL;
}

/** Location of the Wasm binary, relative to this module. */
const WASM_ASSET = "../assets/${assetFile}";

/** Explicitly configured Wasm location, if any. */
let wasmUrl: string | URL | undefined;

/** Cached initialization, so the Wasm module is loaded at most once. */
let initPromise: Promise<void> | undefined;

/**
 * Loads the Wasm binary and instantiates the module.
 */
async function loadWasm(): Promise<void> {
  const url = wasmUrl ?? new URL(WASM_ASSET, import.meta.url);
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(
      \`svg2${capability}: failed to fetch the Wasm binary from \${url} \` +
        \`(HTTP \${response.status})\`,
    );
  }
  await __wbg_init({
    module_or_path: new Uint8Array(await response.arrayBuffer()),
  });
}

/**
 * Loads the Wasm binary of this capability, optionally from an explicit URL.
 *
 * The call is idempotent: the binary is fetched and instantiated at most
 * once, and the same promise is returned for every later call. Omitting
 * \`wasmUrl\` uses the copy shipped with the package. Call this before the
 * first render whenever the binary is hosted somewhere else.
 *
 * @param options Optional Wasm location overrides.
 * @returns A promise that resolves once the Wasm module is ready.
 * @throws If the binary cannot be fetched, or if a URL is passed after the
 * module has already been initialized.
 *
 * @example Point the loader at a self-hosted binary
 * \`\`\`ts
 * import { initSvg2rgba } from "@tksh/svg2ui8a/svg2rgba";
 *
 * await initSvg2rgba({ wasmUrl: "/wasm/svg2rgba_bg.wasm" });
 * \`\`\`
 */
export async function initSvg2${capability}(
  options?: Svg2${capability}InitOptions,
): Promise<void> {
  if (options?.wasmUrl !== undefined) {
    if (initPromise !== undefined) {
      throw new Error(
        \`svg2${capability}: the Wasm module is already initialized; \` +
          "the Wasm URL must be set before the first render.",
      );
    }
    wasmUrl = options.wasmUrl;
  }
  initPromise ??= loadWasm();
  await initPromise;
}

`;
}

function generateSvg2usvgTs(glue: string): string {
  const inlined = inlineGlue(glue, [
    ["export function svg2usvg(svg) {", "function __wasm_svg2usvg(svg) {"],
  ]);
  return GENERATED_HEADER +
    SVG2USVG_MODULE_DOC +
    inlined +
    "\n" +
    generateWasmLoader("usvg", "svg2usvg_bg.wasm") +
    `/**
 * Parses an SVG document and returns its normalized usvg XML as UTF-8 bytes.
 *
 * The bytes are produced by feature-disabled \`usvg\` with the default
 * \`XmlOptions\` (minimal, deterministic, no pretty-print). They are standard
 * SVG XML, not a proprietary binary format, and re-parse with
 * \`usvg::Tree::from_str\`.
 *
 * @param svg The SVG source to normalize.
 * @returns A promise resolving to the UTF-8 encoded normalized SVG XML.
 * @throws If the SVG cannot be parsed, or if it uses unsupported \`<text>\` or
 * \`<image>\` content.
 *
 * @example Normalize an SVG
 * \`\`\`ts
 * import { svg2usvg } from "@tksh/svg2ui8a/svg2usvg";
 *
 * const xml = await svg2usvg('<svg xmlns="http://www.w3.org/2000/svg"/>');
 * console.log(new TextDecoder().decode(xml));
 * \`\`\`
 */
export async function svg2usvg(svg: string): Promise<Uint8Array> {
  await initSvg2usvg();
  return __wasm_svg2usvg(svg);
}
`;
}

function generateSvg2RgbaTs(glue: string): string {
  const inlined = inlineGlue(glue, [
    ["RgbaResult", "__wasm_RgbaResult"],
    ["Svg2RgbaOptions", "__wasm_Svg2RgbaOptions"],
    [
      "export function svg2rgba(svg, options) {",
      "function __wasm_svg2rgba(svg, options) {",
    ],
    ["export class ", "class "],
  ]);
  return GENERATED_HEADER +
    SVG2RGBA_MODULE_DOC +
    inlined +
    "\n" +
    `/**
 * Options controlling how {@linkcode svg2rgba} rasterizes an SVG.
 */
export interface Svg2RgbaOptions {
  /** Target output width in pixels. Omitted, the natural SVG width is used. */
  width?: number;
  /** Target output height in pixels. Omitted, the natural SVG height is used. */
  height?: number;
  /**
   * Alpha representation of the returned pixels. \`"straight"\` (the default)
   * returns non-premultiplied channels; \`"premultiplied"\` returns the bytes as
   * \`tiny-skia\` produced them.
   */
  alphaMode?: "straight" | "premultiplied";
  /**
   * Source window to rasterize, in canvas coordinates (the space of
   * \`naturalWidth\`/\`naturalHeight\` and the \`abs*BoundingBox\` fields). When
   * omitted, the full natural canvas is rendered. The window may be negative
   * and may exceed the canvas; it is not clipped to it.
   */
  region?: RectF;
}

/**
 * A rectangle in canvas coordinates: the shape of the \`abs*BoundingBox\`
 * result fields and of the \`region\` option.
 */
export interface RectF {
  /** X position in canvas coordinates, mirroring \`usvg::Rect::x()\`. */
  x: number;
  /** Y position in canvas coordinates, mirroring \`usvg::Rect::y()\`. */
  y: number;
  /** Box width, mirroring \`usvg::Rect::width()\`. */
  width: number;
  /** Box height, mirroring \`usvg::Rect::height()\`. */
  height: number;
}

/**
 * The result of a {@linkcode svg2rgba} render.
 */
export interface RgbaResult {
  /** Actual output width in pixels after options were applied. */
  width: number;
  /** Actual output height in pixels after options were applied. */
  height: number;
  /** Natural SVG width before output sizing, in SVG user units. */
  naturalWidth: number;
  /** Natural SVG height before output sizing, in SVG user units. */
  naturalHeight: number;
  /** Alpha mode of the pixels: \`"straight"\` or \`"premultiplied"\`. */
  alphaMode: string;
  /**
   * Raw RGBA pixels: one pixel per four bytes, row-major, top-to-bottom. The
   * length is \`width * height * 4\`.
   */
  pixels: Uint8Array;
  /**
   * Upstream \`usvg::Group::abs_bounding_box()\` of the parsed document root,
   * in canvas coordinates. \`null\` only when the measurement is unavailable;
   * zero-area boxes pass through verbatim.
   */
  absBoundingBox: RectF | null;
  /**
   * Upstream \`usvg::Group::abs_stroke_bounding_box()\` of the parsed document
   * root, in canvas coordinates. \`null\` only when unavailable.
   */
  absStrokeBoundingBox: RectF | null;
  /**
   * Upstream \`usvg::Group::abs_layer_bounding_box()\` of the parsed document
   * root, in canvas units. \`null\` only when unavailable; upstream returns
   * \`0,0,1,1\` for empty groups.
   */
  absLayerBoundingBox: RectF | null;
}

` +
    generateWasmLoader("rgba", "svg2rgba_bg.wasm") +
    `/**
 * Parses an SVG document and renders it to raw RGBA pixels in one shot.
 *
 * There is no intermediate payload and no cacheable-bytes contract beyond
 * "same input, same pixels". The canvas is fully transparent outside the
 * painted shapes.
 *
 * @param svg The SVG source to render.
 * @param options Optional sizing and alpha-mode controls.
 * @returns A promise resolving to the rendered pixels and their dimensions.
 * @throws If the SVG cannot be parsed, uses unsupported \`<text>\` or
 * \`<image>\` content, requests invalid dimensions, has a zero natural size, or
 * exhausts Wasm linear memory.
 *
 * @example Render an SVG to pixels
 * \`\`\`ts
 * import { svg2rgba } from "@tksh/svg2ui8a/svg2rgba";
 *
 * const { pixels, width, height } = await svg2rgba(
 *   '<svg xmlns="http://www.w3.org/2000/svg" width="1" height="1"/>',
 * );
 * console.log(width, height, pixels.length);
 * \`\`\`
 */
export async function svg2rgba(
  svg: string,
  options?: Svg2RgbaOptions,
): Promise<RgbaResult> {
  await initSvg2rgba();
  const opts = new __wasm_Svg2RgbaOptions();
  opts.width = options?.width ?? 0;
  opts.height = options?.height ?? 0;
  opts.alpha_mode = options?.alphaMode ?? "straight";
  opts.region = options?.region !== undefined;
  if (options?.region) {
    opts.region_x = options.region.x;
    opts.region_y = options.region.y;
    opts.region_width = options.region.width;
    opts.region_height = options.region.height;
  }
  const result = __wasm_svg2rgba(svg, opts);
  const rectOrNull = (
    x: number | undefined,
    y: number | undefined,
    width: number | undefined,
    height: number | undefined,
  ): RectF | null =>
    x != null && y != null && width != null && height != null
      ? { x, y, width, height }
      : null;
  try {
    return {
      width: result.width,
      height: result.height,
      naturalWidth: result.natural_width,
      naturalHeight: result.natural_height,
      alphaMode: result.alpha_mode,
      pixels: result.pixels,
      absBoundingBox: rectOrNull(
        result.abs_bounding_box_x,
        result.abs_bounding_box_y,
        result.abs_bounding_box_width,
        result.abs_bounding_box_height,
      ),
      absStrokeBoundingBox: rectOrNull(
        result.abs_stroke_bounding_box_x,
        result.abs_stroke_bounding_box_y,
        result.abs_stroke_bounding_box_width,
        result.abs_stroke_bounding_box_height,
      ),
      absLayerBoundingBox: rectOrNull(
        result.abs_layer_bounding_box_x,
        result.abs_layer_bounding_box_y,
        result.abs_layer_bounding_box_width,
        result.abs_layer_bounding_box_height,
      ),
    };
  } finally {
    result.free();
  }
}
`;
}

function generateModTs(): string {
  return `/**
 * \`@tksh/svg2ui8a\`: turns SVG strings into \`Uint8Array\` payloads.
 *
 * Re-exports the two public functions and their supporting types. Import the
 * subpaths \`@tksh/svg2ui8a/svg2usvg\` or \`@tksh/svg2ui8a/svg2rgba\` to load
 * only the capability you need.
 *
 * @module
 */
import { initSvg2rgba } from "./svg2rgba.ts";
import { initSvg2usvg } from "./svg2usvg.ts";

export { initSvg2rgba } from "./svg2rgba.ts";
export { svg2rgba } from "./svg2rgba.ts";
export type {
  RectF,
  RgbaResult,
  Svg2rgbaInitOptions,
  Svg2RgbaOptions,
} from "./svg2rgba.ts";
export { initSvg2usvg } from "./svg2usvg.ts";
export { svg2usvg } from "./svg2usvg.ts";
export type { Svg2usvgInitOptions } from "./svg2usvg.ts";

/**
 * Initializes the Wasm modules of both capabilities.
 *
 * Each capability loads its own binary; a URL that is omitted falls back to
 * the copy shipped with the package. Both binaries are loaded by this call,
 * so applications that use only one capability should prefer the
 * capability-specific \`initSvg2usvg\` / \`initSvg2rgba\` functions.
 *
 * @param options Optional Wasm location overrides, per capability.
 * @returns A promise that resolves once both Wasm modules are ready.
 * @throws If a binary cannot be fetched, or if a URL is passed after the
 * corresponding module has already been initialized.
 *
 * @example Point both capabilities at self-hosted binaries
 * \`\`\`ts
 * import { initSvg2ui8a } from "@tksh/svg2ui8a";
 *
 * await initSvg2ui8a({
 *   svg2usvgWasmUrl: "/wasm/svg2usvg_bg.wasm",
 *   svg2rgbaWasmUrl: "/wasm/svg2rgba_bg.wasm",
 * });
 * \`\`\`
 */
export async function initSvg2ui8a(options?: {
  /** Location of the \`svg2usvg_bg.wasm\` binary. */
  svg2usvgWasmUrl?: string | URL;
  /** Location of the \`svg2rgba_bg.wasm\` binary. */
  svg2rgbaWasmUrl?: string | URL;
}): Promise<void> {
  await Promise.all([
    initSvg2usvg(
      options?.svg2usvgWasmUrl === undefined
        ? undefined
        : { wasmUrl: options.svg2usvgWasmUrl },
    ),
    initSvg2rgba(
      options?.svg2rgbaWasmUrl === undefined
        ? undefined
        : { wasmUrl: options.svg2rgbaWasmUrl },
    ),
  ]);
}
`;
}

function verifyWasmExports(): void {
  const modules = Object.fromEntries(
    ["svg2usvg", "svg2rgba"].map((crate) => {
      const mod = new WebAssembly.Module(
        Deno.readFileSync(resolve(`../assets/${crate}_bg.wasm`)),
      );
      return [crate, WebAssembly.Module.exports(mod).map((e) => e.name)];
    }),
  );

  for (
    const [crate, expected] of [
      ["svg2usvg", "svg2usvg"],
      ["svg2rgba", "svg2rgba"],
    ] as const
  ) {
    if (!modules[crate].includes(expected)) {
      throw new Error(`${crate}_bg.wasm is missing the ${expected} export`);
    }
    for (const other of ["svg2usvg", "svg2rgba"]) {
      if (other !== expected && modules[crate].includes(other)) {
        throw new Error(`${crate}_bg.wasm contains the ${other} export`);
      }
    }
  }
  console.log("  ✓ two independent Wasm artifacts confirmed");
}

function main(): void {
  Deno.mkdirSync(ASSETS_DIR, { recursive: true });

  console.log(
    `wasm-pack ${run(["wasm-pack", "--version"]).replace("wasm-pack ", "")}`,
  );

  for (const crate of ["svg2rgba", "svg2usvg"]) {
    console.log(`Building ${crate} Wasm...`);
    run([
      "wasm-pack",
      "build",
      resolve(`../crates/${crate}`),
      "--target",
      "web",
    ]);
    Deno.copyFileSync(
      resolve(`../crates/${crate}/pkg/${crate}_bg.wasm`),
      resolve(`../assets/${crate}_bg.wasm`),
    );
    console.log(`  → copied to assets/${crate}_bg.wasm`);
  }

  console.log("Regenerating TypeScript wrappers...");
  Deno.writeTextFileSync(
    resolve("../src/svg2usvg.ts"),
    generateSvg2usvgTs(
      Deno.readTextFileSync(resolve("../crates/svg2usvg/pkg/svg2usvg.js")),
    ),
  );
  Deno.writeTextFileSync(
    resolve("../src/svg2rgba.ts"),
    generateSvg2RgbaTs(
      Deno.readTextFileSync(resolve("../crates/svg2rgba/pkg/svg2rgba.js")),
    ),
  );
  Deno.writeTextFileSync(resolve("../src/mod.ts"), generateModTs());
  console.log(
    "  → wrote src/svg2usvg.ts, src/svg2rgba.ts, src/mod.ts",
  );

  verifyWasmExports();

  runCheck();
  console.log("Build complete.");
}

if (import.meta.main) {
  main();
}
