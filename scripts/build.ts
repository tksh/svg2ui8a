/**
 * Build pipeline for `@tksh/svg2ui8a` (engineering-playbook §2, task.md §16).
 *
 *  1. Compiles the two Wasm crates via `wasm-pack --target web`.
 *  2. Copies the Wasm binaries to `assets/`.
 *  3. Regenerates `src/svg2usvg.ts`, `src/svg2rgba.ts`, and `src/mod.ts`
 *     from the wasm-pack glue. The Wasm bytes are *not* embedded: each
 *     wrapper loads its binary from a separate `.wasm` file, defaulting to
 *     the copy shipped in `assets/` (resolved relative to the module) and
 *     allowing consumers to pass an explicit URL or in-memory bytes
 *     (`docs/plans/wasm-file-delivery.md`).
 *  4. Verifies the two artifacts are independent Wasm modules
 *     (`constitution` §3.9, two independently-loadable capabilities).
 *  5. Runs the CDN-free check; aborts the build on failure.
 *
 * `--ts-only` regenerates only the three TypeScript wrappers from the existing
 * `crates/{crate}/pkg` glue and never invokes `wasm-pack` or overwrites
 * `assets/*.wasm`. `--check` compares the checked-in wrappers with generator
 * output and fails on drift.
 *
 * wasm-pack 0.15.0 is the recorded toolchain version for this script.
 */

import { runCheck } from "./check-cdn-free.ts";

const resolve = (relativePath: string): string =>
  new URL(relativePath, import.meta.url).pathname;
const ROOT = resolve("../");
const ASSETS_DIR = resolve("../assets/");

/** Run a command from `cwd`, returning trimmed stdout; throws on failure. */
function run(argv: string[], cwd = ROOT): string {
  const [cmd, ...args] = argv;
  const res = new Deno.Command(cmd, {
    args,
    cwd,
    stdout: "piped",
    stderr: "piped",
  }).outputSync();
  if (!res.success) {
    const stderr = new TextDecoder().decode(res.stderr);
    throw new Error(`command failed: ${cmd} ${args.join(" ")}\n${stderr}`);
  }
  return new TextDecoder().decode(res.stdout).trim();
}

/**
 * Inline wasm-pack glue so the generated wrapper is self-contained: strip the
 * module header and final export line, and apply the given renames so the
 * glue's symbols never collide with the public API.
 */
function inlineGlue(glue: string, renames: Array<[string, string]>): string {
  let out = glue.replace(/^\/\* @ts-self-types=.*\*\/\s*/, "");
  for (const [from, to] of renames) {
    out = out.replaceAll(from, to);
  }
  return out.replace(/export \{ initSync, __wbg_init as default \};\s*$/, "");
}

